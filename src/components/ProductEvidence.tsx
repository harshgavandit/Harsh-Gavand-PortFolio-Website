import { useState } from "react";
import harnessOutput from "../../public/evidence/banking-harness.json";
import digestHTML from "../../public/evidence/news-digest.html?raw";

const captures: Record<string, { src: string; alt: string }> = {
  "agri-samaj-community-platform": {
    src: "/evidence/agri-samaj-workspace.png",
    alt: "Agri Samaj live Marathi homepage with community business search, entrepreneur registration, directory, and publications",
  },
  "ugc-platform": {
    src: "/evidence/ugc-workspace.png",
    alt: "UGC Content Studio sample workspace showing reference inputs, saved output, and generation status",
  },
  "banking-saas": {
    src: "/evidence/lendflow-workspace.png",
    alt: "LendFlow sample lending workspace showing borrower records and loan review",
  },
  "github-replica": {
    src: "/evidence/devgraph-workspace.png",
    alt: "DevGraph sample explorer showing repository discovery and issue records",
  },
};

export function ProductEvidence({ slug }: { slug: string }) {
  const [scenarioId, setScenarioId] = useState(harnessOutput.scenarios[0].id);
  const scenario = harnessOutput.scenarios.find(
    (item) => item.id === scenarioId,
  )!;
  if (slug === "banking-agent-harness")
    return (
      <figure className="harness-evidence">
        <figcaption>
          Deterministic policy replay{" "}
          <span>Sample accounts · in-memory ledger</span>
        </figcaption>
        <div
          role="group"
          aria-label="Banking harness scenario"
          className="evidence-controls"
        >
          {harnessOutput.scenarios.map((item) => (
            <button
              key={item.id}
              type="button"
              aria-pressed={item.id === scenarioId}
              onClick={() => setScenarioId(item.id)}
            >
              {item.label}
            </button>
          ))}
        </div>
        <ol className="harness-steps">
          {scenario.steps.map((step) => (
            <li key={step.label}>
              <strong>{step.label}</strong>
              <span>{step.value}</span>
            </li>
          ))}
        </ol>
        <p role="status" className="evidence-outcome">
          {scenario.outcome}
        </p>
        <details className="artifact-provenance">
          <summary>Scenario data</summary>
          <p className="evidence-caption">
            Saved runs using in-memory accounts.
          </p>
          <a className="text-link" href="/evidence/banking-harness.json">
            View scenario JSON ↗
          </a>
        </details>
      </figure>
    );
  if (slug === "news-automation")
    return (
      <figure className="digest-evidence">
        <figcaption>
          Sample email digest <span>HTML &amp; plaintext output</span>
        </figcaption>
        <iframe
          srcDoc={digestHTML}
          title="Sample AI news digest generated by the project email formatter"
          sandbox=""
          loading="lazy"
        />
        <a
          className="text-link"
          href="/evidence/news-digest.html"
          target="_blank"
          rel="noopener noreferrer"
        >
          Read complete sample digest ↗
        </a>
        <p className="evidence-caption">
          Sample content rendered by the email formatter. No email is sent from
          this preview.
        </p>
      </figure>
    );
  const capture = captures[slug];
  return capture ? (
    <figure className="capture-evidence">
      <img
        src={capture.src}
        width={1280}
        height={900}
        alt={capture.alt}
        loading="lazy"
      />
      <figcaption>
        {slug === "agri-samaj-community-platform"
          ? "Agri Samaj live website · Marathi–English community platform"
          : "Public demo workspace with sample data."}
      </figcaption>
    </figure>
  ) : null;
}
