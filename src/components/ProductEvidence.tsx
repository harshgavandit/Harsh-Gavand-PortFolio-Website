import digestHTML from "../../public/evidence/news-digest.html?raw";
import { deploymentShowcase } from "../data/deploymentShowcase";
import { projects } from "../data/portfolio";
import { AgriConnectGallery } from "./AgriConnectGallery";

const captures: Record<
  string,
  {
    src: string;
    alt: string;
    width?: number;
    height?: number;
    caption?: string;
  }
> = {
  ...Object.fromEntries(
    deploymentShowcase.map((item) => [
      projects.find((project) => project.id === item.projectId)!.slug,
      {
        src: `/evidence/${item.capture}`,
        alt: item.alt,
        width: item.captureWidth ?? 1265,
        height: item.captureHeight ?? 712,
        caption: `Live website capture · ${item.verifiedOn ?? "20 October 2026"} · Click to enlarge`,
      },
    ]),
  ),
  "agri-samaj-community-platform": {
    src: "/evidence/agri-samaj-workspace.png",
    alt: "Agri Samaj live Marathi homepage with community business search, entrepreneur registration, directory, and publications",
  },
  "ugc-platform": {
    src: "/evidence/ugc-workspace.png",
    alt: "UGC Content Studio sample workspace showing reference inputs, saved output, and generation status",
  },
  "banking-saas": {
    src: "/evidence/lendflow-workspace.png",
    alt: "LendFlow sample lending workspace showing borrower records and loan review",
  },
  "github-replica": {
    src: "/evidence/devgraph-workspace.png",
    alt: "DevGraph sample explorer showing repository discovery and issue records",
  },
};

export function ProductEvidence({ slug }: { slug: string }) {
  if (slug === "agri-connect") return <AgriConnectGallery />;
  if (slug === "news-automation")
    return (
      <figure className="digest-evidence">
        <figcaption>
          Sample email digest <span>HTML &amp; plaintext output</span>
        </figcaption>
        <iframe
          srcDoc={digestHTML}
          title="Sample AI news digest generated by the project email formatter"
          sandbox=""
          loading="lazy"
        />
        <a
          className="text-link"
          href="/evidence/news-digest.html"
          target="_blank"
          rel="noopener noreferrer"
        >
          Read complete sample digest ↗
        </a>
      </figure>
    );
  const capture = captures[slug];
  return capture ? (
    <figure className="capture-evidence">
      <a
        href={capture.src}
        target="_blank"
        rel="noopener noreferrer"
        aria-label={`Enlarge ${slug} website screenshot`}
      >
        <img
          src={capture.src}
          width={capture.width ?? 1280}
          height={capture.height ?? 900}
          alt={capture.alt}
          loading="lazy"
        />
      </a>
      {capture.caption && <figcaption>{capture.caption}</figcaption>}
    </figure>
  ) : null;
}
